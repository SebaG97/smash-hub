"""The single catalog of achievements (SH-ACH-01, docs/logros/catalogo.md).

Code, not a table: identifiers, names and conditions live here and the web reads them
from GET /api/v1/achievements/catalog. The 25 achievements that existed before keep their
identifiers, names and conditions (``legacy=True``).

Who receives an achievement:
- ``player``: a hub player (players.id, resolved from the start.gg player id), stored in
  player_achievements by the evaluator (app.achievements.rules) or granted by hand.
- ``prode``: an account, stored in prode_achievements when a Prode is settled.

``status``:
- ``active``: evaluated automatically (subject to its collection being enabled).
- ``manual``: only organizers grant it, with a public reason.
- ``pending``: registered but never evaluated nor granted (missing data or validation).
``kind``: ``permanent`` (kept once earned), ``state`` (computed live, can be lost) or
``limited`` (a limited edition, outside collection progress).
"""

