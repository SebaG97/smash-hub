@dataclass(frozen=True)
class Achievement:
    id: str
    scope: str  # player | prode
    category: str
    name: str
    description: str
    condition: str
    rarity: str
    status: str = "active"
    kind: str = "permanent"
    secret: bool = False
    humor: bool = False
    origin: str = "creativa"  # existente | creativa | paraguaya | meme
    collection: str | None = None
    universe: str = "players"
    partial: bool = False  # depends on data that only some sets have
    legacy: bool = False
    tone: str | None = None  # colour of the old player badges (gold, fire, bone)
    pending: str | None = None  # why it is not active yet


def _a(*args, **kwargs):
    return Achievement(*args, **kwargs)


