BY_ID = {a.id: a for a in ACHIEVEMENTS}
LEGACY_IDS = [a.id for a in ACHIEVEMENTS if a.legacy]


def get(achievement_id):
    return BY_ID.get(achievement_id)


def view(a, *, active_collections=None):
    """Public view of one entry. A gated collection off marks its entries unavailable."""
    data = asdict(a)
    gate = GATED.get(a.collection) if a.collection else None
    data["available"] = a.status != "pending" and (
        gate is None or (active_collections is not None and gate in active_collections)
    )
    data["category_name"] = CATEGORIES[a.category]
    data["rarity_name"] = RARITIES[a.rarity]
    data["collection_name"] = COLLECTIONS.get(a.collection) if a.collection else None
    return data
